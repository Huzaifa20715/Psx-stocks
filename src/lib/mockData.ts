export function generateHistoricalData(symbol: string, days: number): OHLCVData[] {
  const stock = psxStocks.find((s) => s.symbol === symbol)
  if (!stock) return []

  const data: OHLCVData[] = []
  let price = stock.price * 0.8 // Start from 80% of current price
  const volatility = 0.02 // 2% daily volatility

  // Use a simple deterministic seed based on symbol
  const seed = symbol.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0)

  for (let i = days; i >= 0; i--) {
    const date = new Date()
    date.setDate(date.getDate() - i)

    // Skip weekends
    if (date.getDay() === 0 || date.getDay() === 6) continue

    // Pseudo-random using sine functions for determinism
    const dayIndex = days - i
    const rand1 = Math.sin(seed * dayIndex * 0.1) * 0.5 + 0.5
    const rand2 = Math.sin(seed * dayIndex * 0.2 + 1) * 0.5 + 0.5
    const rand3 = Math.sin(seed * dayIndex * 0.3 + 2) * 0.5 + 0.5

    const changePercent = (rand1 - 0.5) * 2 * volatility
    price = price * (1 + changePercent)

    // Ensure price trends toward current price
    const targetRatio = stock.price / price
    price = price * (1 + (targetRatio - 1) * 0.01)

    const open = price
    const high = price * (1 + rand2 * volatility * 0.5)
    const low = price * (1 - rand3 * volatility * 0.5)
    const close = price * (1 + (rand1 - 0.48) * volatility * 0.3)
    const volume = Math.floor(stock.volume * (0.5 + rand1))

    data.push({
      date: date.toISOString().split('T')[0],
      open: Math.round(open * 100) / 100,
      high: Math.round(Math.max(open, high, close) * 100) / 100,
      low: Math.round(Math.min(open, low, close) * 100) / 100,
      close: Math.round(close * 100) / 100,
      volume,
    })
  }

  return data
}

export function getTopGainers(count = 5): Stock[] {
  return [...psxStocks]
    .filter((s) => s.changePercent > 0)
    .sort((a, b) => b.changePercent - a.changePercent)
    .slice(0, count)
}

export function getTopLosers(count = 5): Stock[] {
  return [...psxStocks]
    .filter((s) => s.changePercent < 0)
    .sort((a, b) => a.changePercent - b.changePercent)
    .slice(0, count)
}

export function getVolumeLeaders(count = 5): Stock[] {
  return [...psxStocks]
    .sort((a, b) => b.volume - a.volume)
    .slice(0, count)
}

export function getSimilarStocks(symbol: string, count = 4): Stock[] {
  const stock = psxStocks.find((s) => s.symbol === symbol)
  if (!stock) return []
  return psxStocks
    .filter((s) => s.sector === stock.sector && s.symbol !== symbol)
    .slice(0, count)
}
